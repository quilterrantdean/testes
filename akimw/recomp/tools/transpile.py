#!/usr/bin/env python3
"""Converte a desmontagem z80dasm em uma imagem ROM C estática verificável."""
from __future__ import print_function

import pathlib
import re
import sys

BANK_SIZE = 0x4000
BYTE_COMMENT = re.compile(r";\s*([0-9A-Fa-f]{4,5})\s+((?:[0-9A-Fa-f]{2}\s*)+)")


def parse_bank(path):
    image = bytearray([0xFF]) * BANK_SIZE
    base = None
    for number, line in enumerate(path.read_text(encoding="latin-1").splitlines(), 1):
        match = BYTE_COMMENT.search(line)
        if not match:
            continue
        address = int(match.group(1), 16)
        data = bytes(int(value, 16) for value in match.group(2).split())
        if base is None:
            base = address
        offset = address - base
        if offset < 0 or offset + len(data) > BANK_SIZE:
            raise ValueError("%s:%d: instrução fora do banco" % (path, number))
        image[offset:offset + len(data)] = data
    if base is None:
        raise ValueError("%s: não foram encontrados bytes z80dasm" % path)
    return image


def emit(output, image):
    rows = []
    for offset in range(0, len(image), 16):
        values = ", ".join("0x%02X" % value for value in image[offset:offset + 16])
        rows.append("    " + values + ",")
    output.write("/* Generated by tools/transpile.py; do not edit. */\n")
    output.write("#include <stddef.h>\n#include <stdint.h>\n\n")
    output.write("const uint8_t recomp_rom[%d] = {\n%s\n};\n" % (len(image), "\n".join(rows)))
    output.write("const size_t recomp_rom_size = sizeof(recomp_rom);\n")


def main():
    root = pathlib.Path(__file__).resolve().parent.parent.parent
    image = bytearray()
    for bank in range(8):
        image.extend(parse_bank(root / ("bank%d.asm" % bank)))
    destination = root / "recomp" / "generated" / "game_rom.c"
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("w", encoding="ascii", newline="\n") as output:
        emit(output, image)
    print("%s: %d bytes" % (destination, len(image)))


if __name__ == "__main__":
    main()
